// scripts/bundle.mjs — zero-dependency concatenator.
//
// Concatenates lib/src/*.js into lib/client.js in dependency order, wrapping the
// bodies in the __ModuleLoader__ factory. This mirrors the official
// @deepseek-ai/dsh-* "#region" concatenation model: no bundler, no transpiler,
// the output ships inside the plugin tgz and is served by dsh's client-module
// host through combo URLs (see the HEAD note below).
//
// Run with `node scripts/bundle.mjs` (also wired as `prepack` so `pnpm pack`
// always rebuilds). Module bodies run in one shared factory scope, so they may
// reference `React` (from the wrapper) and one another; order matters.
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const srcDir = resolve(root, "lib", "src")
const outFile = resolve(root, "lib", "client.js")

const ORDER = [
  "styles.js",
  "store.js",
  "parser.js",
  "selection.js",
  "panel.js",
  "files.js",
  "documents.js",
  "toolbar.js",
  "blocks.js",
  "viewer.js",
  "sidebar.js",
  "entry.js"
]

const HEAD = `// dsh-md-annotator client half
//
// A \`dsh.client\` module in the __ModuleLoader__ factory form. This file is
// GENERATED by scripts/bundle.mjs from lib/src/*.js (no bundler/transpiler,
// plain concatenation). dsh serves it through combo URLs of the form
// \`/plugins/??<id>/client.js,...&rev=<hash>\` — since dsh 0.1.2-alpha.4 a bare
// /plugins/dsh-md-annotator/client.js path 404s by design (combo-only
// distribution; the bare path survives only as a source-map fallback name).
// Registers a Markdown file viewer through The Better Sidebar.
window.__ModuleLoader__.load({
  id: "dsh-md-annotator",
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" })
    var React = require("react")
    var ReactDOM = require("react-dom")
`

const TAIL = `    return module.exports
  }
})
`

const parts = []
for (const name of ORDER) {
  const body = readFileSync(resolve(srcDir, name), "utf8")
  const indented = body.split("\n").map((line) => line === "" ? "" : "    " + line).join("\n")
  parts.push(`    //#region src/${name}\n${indented}\n    //#endregion`)
}

const out = HEAD + parts.join("\n") + "\n" + TAIL
writeFileSync(outFile, out, "utf8")
console.log(`bundle: wrote ${outFile} (${out.length} bytes)`)
